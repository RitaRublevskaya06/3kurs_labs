CREATE OR REPLACE PROCEDURE sp_GenerateTourReportXML (
    p_StartDate IN DATE,
    p_EndDate IN DATE,
    p_xml_result OUT XMLTYPE
)
IS
BEGIN
    SELECT XMLELEMENT("ToursReport",
        XMLATTRIBUTES(
            CURRENT_TIMESTAMP AS "ReportGenerated",
            TO_CHAR(p_StartDate, 'YYYY-MM-DD') AS "StartDate",
            TO_CHAR(p_EndDate, 'YYYY-MM-DD') AS "EndDate"
        ),
        XMLAGG(
            XMLELEMENT("Tour",
                XMLATTRIBUTES(t.id AS "id"),
                XMLELEMENT("Name", t.title),
                XMLELEMENT("Country", c.name),
                XMLELEMENT("Hotel", h.name),
                XMLELEMENT("Stars", h.stars),
                XMLELEMENT("DepartureDate", TO_CHAR(t.departure_date, 'YYYY-MM-DD')),
                XMLELEMENT("BasePrice", t.base_price),
                XMLELEMENT("BookingsCount", NVL(b.BookingCount, 0)),
                XMLELEMENT("TotalRevenue", NVL(b.TotalRevenue, 0)),
                XMLELEMENT("AverageCheck", ROUND(NVL(b.AvgCheck, 0), 2))
            )
        )
    )
    INTO p_xml_result
    FROM Tour t
    INNER JOIN Country c ON t.country_id = c.id
    INNER JOIN Hotel h ON t.hotel_id = h.id
    LEFT JOIN (
        SELECT 
            tour_id,
            COUNT(*) AS BookingCount,
            SUM(total_price) AS TotalRevenue,
            AVG(total_price) AS AvgCheck
        FROM Booking
        GROUP BY tour_id
    ) b ON t.id = b.tour_id
    WHERE t.departure_date BETWEEN p_StartDate AND p_EndDate;
END sp_GenerateTourReportXML;
/

