CREATE OR REPLACE PROCEDURE sp_InsertXMLReport (
    p_StartDate IN DATE,
    p_EndDate IN DATE,
    p_new_id OUT NUMBER
)
IS
    v_xml XMLTYPE;
BEGIN
    sp_GenerateTourReportXML(p_StartDate, p_EndDate, v_xml);

    INSERT INTO Report (xml_data)
    VALUES (v_xml)
    RETURNING id INTO p_new_id;
    
    COMMIT;
    
    DBMS_OUTPUT.PUT_LINE('Report inserted with ID: ' || p_new_id);
END sp_InsertXMLReport;
/

