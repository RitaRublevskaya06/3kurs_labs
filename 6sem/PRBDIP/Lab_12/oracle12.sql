CREATE OR REPLACE PROCEDURE sp_ExtractXMLValue (
    p_TourName IN VARCHAR2 DEFAULT NULL,
    p_MinRevenue IN NUMBER DEFAULT NULL,
    p_results OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN p_results FOR
        SELECT 
            r.id AS ReportID,
            r.created_at,
            EXTRACTVALUE(VALUE(t), '/Tour/Name') AS TourName,
            EXTRACTVALUE(VALUE(t), '/Tour/Country') AS Country,
            EXTRACTVALUE(VALUE(t), '/Tour/Hotel') AS Hotel,
            TO_NUMBER(EXTRACTVALUE(VALUE(t), '/Tour/Stars')) AS Stars,
            EXTRACTVALUE(VALUE(t), '/Tour/DepartureDate') AS DepartureDate,
            TO_NUMBER(EXTRACTVALUE(VALUE(t), '/Tour/BasePrice')) AS BasePrice,
            TO_NUMBER(EXTRACTVALUE(VALUE(t), '/Tour/BookingsCount')) AS BookingsCount,
            TO_NUMBER(EXTRACTVALUE(VALUE(t), '/Tour/TotalRevenue')) AS TotalRevenue,
            TO_NUMBER(EXTRACTVALUE(VALUE(t), '/Tour/AverageCheck')) AS AverageCheck
        FROM Report r,
             TABLE(XMLSEQUENCE(EXTRACT(r.xml_data, '/ToursReport/Tour'))) t
        WHERE (p_TourName IS NULL OR UPPER(EXTRACTVALUE(VALUE(t), '/Tour/Name')) LIKE '%' || UPPER(p_TourName) || '%')
          AND (p_MinRevenue IS NULL OR TO_NUMBER(EXTRACTVALUE(VALUE(t), '/Tour/TotalRevenue')) >= p_MinRevenue)
        ORDER BY r.id, TotalRevenue DESC;
END sp_ExtractXMLValue;
/


DECLARE
    v_cursor SYS_REFCURSOR;
    v_ReportID NUMBER;
    v_CreatedAt TIMESTAMP;
    v_TourName VARCHAR2(255);
    v_Country VARCHAR2(100);
    v_Hotel VARCHAR2(200);
    v_Stars NUMBER;
    v_DepartureDate VARCHAR2(10);
    v_BasePrice NUMBER;
    v_BookingsCount NUMBER;
    v_TotalRevenue NUMBER;
    v_AverageCheck NUMBER;
BEGIN
    sp_ExtractXMLValue(NULL, NULL, v_cursor);
    
    DBMS_OUTPUT.PUT_LINE('=== TOUR REPORT ===');
    LOOP
        FETCH v_cursor INTO v_ReportID, v_CreatedAt, v_TourName, v_Country, 
                           v_Hotel, v_Stars, v_DepartureDate, v_BasePrice,
                           v_BookingsCount, v_TotalRevenue, v_AverageCheck;
        EXIT WHEN v_cursor%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('Tour: ' || v_TourName || ' | Country: ' || v_Country || 
                             ' | Bookings: ' || v_BookingsCount || ' | Revenue: ' || v_TotalRevenue);
    END LOOP;
    CLOSE v_cursor;
END;
/

