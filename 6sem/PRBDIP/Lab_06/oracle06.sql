-- 3. Вычисление итогов предоставленных услуг помесячно, за квартал, за полгода, за год
SELECT DISTINCT
    EXTRACT(YEAR FROM b.booking_date) AS "Год",
    EXTRACT(MONTH FROM b.booking_date) AS "Месяц",
    TO_CHAR(b.booking_date, 'Month', 'NLS_DATE_LANGUAGE=RUSSIAN') AS "Название месяца",
    SUM(b.total_price) OVER (PARTITION BY EXTRACT(YEAR FROM b.booking_date), EXTRACT(MONTH FROM b.booking_date)) AS "Итог за месяц",
    SUM(b.total_price) OVER (PARTITION BY EXTRACT(YEAR FROM b.booking_date), 
        CASE 
            WHEN EXTRACT(MONTH FROM b.booking_date) BETWEEN 1 AND 3 THEN 1
            WHEN EXTRACT(MONTH FROM b.booking_date) BETWEEN 4 AND 6 THEN 2
            WHEN EXTRACT(MONTH FROM b.booking_date) BETWEEN 7 AND 9 THEN 3
            ELSE 4
        END) AS "Итог за квартал",
    SUM(b.total_price) OVER (PARTITION BY EXTRACT(YEAR FROM b.booking_date),
        CASE WHEN EXTRACT(MONTH FROM b.booking_date) <= 6 THEN 1 ELSE 2 END) AS "Итог за полугодие",
    SUM(b.total_price) OVER (PARTITION BY EXTRACT(YEAR FROM b.booking_date)) AS "Итог за год",
    COUNT(b.id) OVER (PARTITION BY EXTRACT(YEAR FROM b.booking_date), EXTRACT(MONTH FROM b.booking_date)) AS "Количество бронирований"
FROM Booking b
INNER JOIN OrderStatus os ON b.status_id = os.id
WHERE os.name IN ('completed', 'paid')
    AND b.booking_date >= DATE '2023-01-01'
ORDER BY "Год", "Месяц";
/

-- 4. Вычисление итогов за период с процентами
WITH MonthlySales AS (
    SELECT 
        TO_CHAR(b.booking_date, 'YYYY-MM') AS "Период",
        SUM(b.total_price) AS "Объем услуг за период",
        COUNT(b.id) AS "Количество услуг"
    FROM Booking b
    INNER JOIN OrderStatus os ON b.status_id = os.id
    WHERE os.name IN ('completed', 'paid')
        AND b.booking_date BETWEEN DATE '2024-01-01' AND DATE '2024-12-31'
    GROUP BY TO_CHAR(b.booking_date, 'YYYY-MM')
),
TotalStats AS (
    SELECT 
        SUM("Объем услуг за период") AS "Общий объем",
        MAX("Объем услуг за период") AS "Максимальный объем"
    FROM MonthlySales
)
SELECT 
    ms."Период",
    ms."Количество услуг",
    ms."Объем услуг за период",
    ts."Общий объем",
    ROUND(ms."Объем услуг за период" * 100 / NULLIF(ts."Общий объем", 0), 2) AS "Процент от общего (%)",
    ts."Максимальный объем",
    ROUND(ms."Объем услуг за период" * 100 / NULLIF(ts."Максимальный объем", 0), 2) AS "Процент от максимума (%)"
FROM MonthlySales ms
CROSS JOIN TotalStats ts
ORDER BY ms."Период";
/


-- 5. ROW_NUMBER() для пагинации (по 20 строк)
SELECT 
    t.id AS "ID",
    t.title AS "Название тура",
    t.base_price AS "Цена (руб.)",
    t.duration_days AS "Длительность (дней)",
    t.departure_date AS "Дата отправления",
    c.name AS "Страна назначения"
FROM Tour t
INNER JOIN Country c ON t.country_id = c.id
WHERE t.is_active = 1
AND ROWNUM <= 20
ORDER BY t.id;
