-- 7. Для каждого клиента - 6 самых посещаемых стран
WITH ClientCountryVisits AS (
    SELECT 
        u.id AS ClientId,
        u.first_name || ' ' || u.last_name AS Клиент,
        c.name AS Страна,
        COUNT(b.id) AS КоличествоПосещений,
        ROW_NUMBER() OVER (PARTITION BY u.id ORDER BY COUNT(b.id) DESC) AS RankInClient
    FROM Booking b
    INNER JOIN Client cl ON b.client_id = cl.user_id
    INNER JOIN "User" u ON cl.user_id = u.id
    INNER JOIN Tour t ON b.tour_id = t.id
    INNER JOIN Country c ON t.country_id = c.id
    INNER JOIN OrderStatus os ON b.status_id = os.id
    WHERE os.name IN ('completed', 'paid')
    GROUP BY u.id, u.first_name, u.last_name, c.name
),
Top6Countries AS (
    SELECT Страна, COUNT(*) AS ОбщаяПопулярность
    FROM ClientCountryVisits
    GROUP BY Страна
    ORDER BY ОбщаяПопулярность DESC
    FETCH FIRST 6 ROWS ONLY
),
AllClients AS (
    SELECT DISTINCT ClientId, Клиент FROM ClientCountryVisits
)
SELECT 
    ac.Клиент AS "Клиент",
    t6.Страна AS "Страна",
    NVL(ccv.КоличествоПосещений, 0) AS "Количество посещений",
    ccv.RankInClient AS "Ранг у клиента",
    t6.ОбщаяПопулярность AS "Общая популярность"
FROM Top6Countries t6
CROSS JOIN AllClients ac
LEFT JOIN ClientCountryVisits ccv ON ccv.ClientId = ac.ClientId AND ccv.Страна = t6.Страна
ORDER BY ac.Клиент, t6.ОбщаяПопулярность DESC;
/


