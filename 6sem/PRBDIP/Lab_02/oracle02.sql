-- =====================================================
-- 1. СОЗДАНИЕ ТАБЛИЦ
-- =====================================================
-- Таблица 1: User (Пользователи)
CREATE TABLE "User" (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR2(255) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    first_name VARCHAR2(100) NOT NULL,
    last_name VARCHAR2(100) NOT NULL,
    phone VARCHAR2(20),
    registration_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    last_login TIMESTAMP,
    role VARCHAR2(20) NOT NULL CHECK (role IN ('client', 'manager'))
);

-- Таблица 2: Client (Клиенты)
CREATE TABLE Client (
    user_id NUMBER PRIMARY KEY,
    passport_number VARCHAR2(50) NOT NULL,
    passport_issue_date DATE NOT NULL,
    passport_expiry_date DATE NOT NULL,
    date_of_birth DATE NOT NULL,
    loyalty_points NUMBER DEFAULT 0,
    client_since DATE,
    CONSTRAINT fk_client_user FOREIGN KEY (user_id) REFERENCES "User"(id) ON DELETE CASCADE
);

-- Таблица 3: Manager (Менеджеры)
CREATE TABLE Manager (
    user_id NUMBER PRIMARY KEY,
    employee_id VARCHAR2(20) NOT NULL UNIQUE,
    hire_date DATE NOT NULL,
    department VARCHAR2(100),
    commission_rate NUMBER(5,2) DEFAULT 0.0,
    CONSTRAINT fk_manager_user FOREIGN KEY (user_id) REFERENCES "User"(id) ON DELETE CASCADE
);

-- Таблица 4: Country (Страны)
CREATE TABLE Country (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL UNIQUE,
    code CHAR(2) UNIQUE,
    visa_required NUMBER(1) DEFAULT 0 CHECK (visa_required IN (0,1)),
    description CLOB,
    is_popular NUMBER(1) DEFAULT 0 CHECK (is_popular IN (0,1))
);

-- Таблица 5: Hotel (Отели)
CREATE TABLE Hotel (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(200) NOT NULL,
    country_id NUMBER NOT NULL,
    city VARCHAR2(100) NOT NULL,
    stars NUMBER(1) CHECK (stars BETWEEN 1 AND 5),
    food_type VARCHAR2(50) CHECK (food_type IN ('RO', 'BB', 'HB', 'FB', 'AI')),
    rating NUMBER(3,1) CHECK (rating BETWEEN 0 AND 5),
    address CLOB,
    contact_phone VARCHAR2(20),
    CONSTRAINT fk_hotel_country FOREIGN KEY (country_id) REFERENCES Country(id)
);

-- Таблица 6: TourType (Типы туров)
CREATE TABLE TourType (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL UNIQUE,
    description CLOB,
    seasonality VARCHAR2(20) CHECK (seasonality IN ('summer', 'winter', 'all')),
    activity_level VARCHAR2(20) CHECK (activity_level IN ('low', 'medium', 'high'))
);

-- Таблица 7: Flight (Рейсы)
CREATE TABLE Flight (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airline VARCHAR2(150) NOT NULL,
    flight_number VARCHAR2(10) NOT NULL,
    departure_airport VARCHAR2(100) NOT NULL,
    arrival_airport VARCHAR2(100) NOT NULL,
    departure_datetime TIMESTAMP NOT NULL,
    arrival_datetime TIMESTAMP NOT NULL,
    flight_class VARCHAR2(50) CHECK (flight_class IN ('economy', 'business', 'first')),
    is_included NUMBER(1) DEFAULT 1 CHECK (is_included IN (0,1))
);

-- Таблица 8: Tour (Туры)
CREATE TABLE Tour (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(255) NOT NULL,
    description CLOB,
    tour_type_id NUMBER,
    country_id NUMBER NOT NULL,
    hotel_id NUMBER NOT NULL,
    flight_id NUMBER,
    duration_days NUMBER NOT NULL,
    departure_date DATE NOT NULL,
    base_price NUMBER(10,2) NOT NULL,
    available_seats NUMBER NOT NULL,
    is_active NUMBER(1) DEFAULT 1 CHECK (is_active IN (0,1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_tour_type FOREIGN KEY (tour_type_id) REFERENCES TourType(id),
    CONSTRAINT fk_tour_country FOREIGN KEY (country_id) REFERENCES Country(id),
    CONSTRAINT fk_tour_hotel FOREIGN KEY (hotel_id) REFERENCES Hotel(id),
    CONSTRAINT fk_tour_flight FOREIGN KEY (flight_id) REFERENCES Flight(id)
);

-- Таблица 9: OrderStatus (Статусы заказов)
CREATE TABLE OrderStatus (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(50) NOT NULL UNIQUE,
    description CLOB,
    is_final NUMBER(1) DEFAULT 0 CHECK (is_final IN (0,1))
);

-- Таблица 10: Booking (Заказы/Бронирования)
CREATE TABLE Booking (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_number VARCHAR2(50) NOT NULL UNIQUE,
    client_id NUMBER NOT NULL,
    tour_id NUMBER NOT NULL,
    manager_id NUMBER,
    booking_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    status_id NUMBER NOT NULL,
    persons_count NUMBER DEFAULT 1,
    total_price NUMBER(10,2) NOT NULL,
    CONSTRAINT fk_booking_client FOREIGN KEY (client_id) REFERENCES Client(user_id),
    CONSTRAINT fk_booking_tour FOREIGN KEY (tour_id) REFERENCES Tour(id),
    CONSTRAINT fk_booking_manager FOREIGN KEY (manager_id) REFERENCES Manager(user_id),
    CONSTRAINT fk_booking_status FOREIGN KEY (status_id) REFERENCES OrderStatus(id)
);

-- Таблица 11: Payment (Платежи)
CREATE TABLE Payment (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id NUMBER NOT NULL,
    amount NUMBER(10,2) NOT NULL,
    payment_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    payment_method VARCHAR2(50) NOT NULL CHECK (payment_method IN ('card', 'transfer', 'cash')),
    status VARCHAR2(50) NOT NULL CHECK (status IN ('pending', 'completed', 'failed', 'refunded')),
    transaction_id VARCHAR2(255),
    CONSTRAINT fk_payment_booking FOREIGN KEY (booking_id) REFERENCES Booking(id)
);

-- Таблица 12: Review (Отзывы)
CREATE TABLE Review (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id NUMBER NOT NULL UNIQUE,
    client_id NUMBER NOT NULL,
    tour_id NUMBER NOT NULL,
    rating NUMBER(1) NOT NULL CHECK (rating BETWEEN 1 AND 5),
    review_comment CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    is_approved NUMBER(1) DEFAULT 0 CHECK (is_approved IN (0,1)),
    CONSTRAINT fk_review_booking FOREIGN KEY (booking_id) REFERENCES Booking(id),
    CONSTRAINT fk_review_client FOREIGN KEY (client_id) REFERENCES Client(user_id),
    CONSTRAINT fk_review_tour FOREIGN KEY (tour_id) REFERENCES Tour(id)
);
/

