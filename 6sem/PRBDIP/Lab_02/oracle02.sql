-- 3. ПРЕДСТАВЛЕНИЯ
-- =====================================================
CREATE OR REPLACE VIEW V_ACTIVE_TOURS AS
SELECT
    t.id AS TourId,
    t.title,
    t.base_price,
    t.duration_days,
    t.departure_date,
    t.available_seats,
    c.name AS Country,
    h.name AS Hotel,
    h.stars,
    tt.name AS TourType
FROM Tour t
INNER JOIN Country c ON t.country_id = c.id
INNER JOIN Hotel h ON t.hotel_id = h.id
LEFT JOIN TourType tt ON t.tour_type_id = tt.id
WHERE t.is_active = 1;
/

CREATE OR REPLACE VIEW V_BOOKING_REPORT AS
SELECT
    b.booking_number,
    u.first_name || ' ' || u.last_name AS ClientName,
    t.title AS TourTitle,
    b.booking_date,
    os.name AS Status,
    b.persons_count,
    b.total_price,
    p.amount AS PaidAmount,
    p.status AS PaymentStatus
FROM Booking b
INNER JOIN Client c ON b.client_id = c.user_id
INNER JOIN "User" u ON c.user_id = u.id
INNER JOIN Tour t ON b.tour_id = t.id
INNER JOIN OrderStatus os ON b.status_id = os.id
LEFT JOIN Payment p ON b.id = p.booking_id;
/

