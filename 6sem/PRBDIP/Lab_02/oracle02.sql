-- Функция 1: Возраст клиента
CREATE OR REPLACE FUNCTION FN_GET_CLIENT_AGE (
    p_client_id IN Client.user_id%TYPE
) RETURN NUMBER IS
    v_age NUMBER;
BEGIN
    SELECT FLOOR(MONTHS_BETWEEN(SYSDATE, date_of_birth) / 12)
    INTO v_age
    FROM Client
    WHERE user_id = p_client_id;
    RETURN v_age;
END FN_GET_CLIENT_AGE;
/

-- Функция 2: Проверка доступности мест
CREATE OR REPLACE FUNCTION FN_CHECK_SEAT_AVAILABILITY (
    p_tour_id IN Tour.id%TYPE,
    p_requested_seats IN Tour.available_seats%TYPE
) RETURN NUMBER IS
    v_available_seats Tour.available_seats%TYPE;
BEGIN
    SELECT available_seats INTO v_available_seats
    FROM Tour
    WHERE id = p_tour_id;

    IF v_available_seats >= p_requested_seats THEN
        RETURN 1;
    ELSE
        RETURN 0;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
END FN_CHECK_SEAT_AVAILABILITY;
/

-- Функция 3: Прибыльность тура
CREATE OR REPLACE FUNCTION FN_GET_TOUR_PROFITABILITY (
    p_tour_id IN Tour.id%TYPE
) RETURN NUMBER IS
    v_profit NUMBER := 0;
BEGIN
    SELECT NVL(SUM(p.amount), 0) - (t.base_price * COUNT(DISTINCT b.id))
    INTO v_profit
    FROM Tour t
    LEFT JOIN Booking b ON t.id = b.tour_id
    LEFT JOIN Payment p ON b.id = p.booking_id AND p.status = 'completed'
    WHERE t.id = p_tour_id
    GROUP BY t.base_price;

    RETURN NVL(v_profit, 0);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
END FN_GET_TOUR_PROFITABILITY;
/

-- Функция 4: Рейтинг отелей
CREATE OR REPLACE TYPE hotel_rating_row AS OBJECT (
    id NUMBER,
    HotelName VARCHAR2(200),
    AvgRating NUMBER,
    ReviewCount NUMBER
);
/

CREATE OR REPLACE TYPE hotel_rating_table AS TABLE OF hotel_rating_row;
/

CREATE OR REPLACE FUNCTION FN_GET_HOTEL_RATING_TABLE
RETURN hotel_rating_table PIPELINED IS
    v_rec hotel_rating_row;
BEGIN
    FOR rec IN (
        SELECT
            h.id,
            h.name AS HotelName,
            AVG(r.rating) AS AvgRating,
            COUNT(r.id) AS ReviewCount
        FROM Hotel h
        LEFT JOIN Tour t ON h.id = t.hotel_id
        LEFT JOIN Booking b ON t.id = b.tour_id
        LEFT JOIN Review r ON b.id = r.booking_id AND r.is_approved = 1
        GROUP BY h.id, h.name
        ORDER BY h.id
    ) LOOP
        v_rec := hotel_rating_row(rec.id, rec.HotelName, rec.AvgRating, rec.ReviewCount);
        PIPE ROW (v_rec);
    END LOOP;
    RETURN;
END FN_GET_HOTEL_RATING_TABLE;
/



-- Функция 5: Форматирование имени клиента
CREATE OR REPLACE FUNCTION FN_FORMAT_CLIENT_NAME (
    p_client_id IN Client.user_id%TYPE
) RETURN VARCHAR2 IS
    v_formatted_name VARCHAR2(255);
BEGIN
    SELECT last_name || ' ' || SUBSTR(first_name, 1, 1) || '.'
    INTO v_formatted_name
    FROM "User" u
    INNER JOIN Client c ON u.id = c.user_id
    WHERE c.user_id = p_client_id;
    RETURN v_formatted_name;
END FN_FORMAT_CLIENT_NAME;
/



-- Функция 1: Количество завершенных бронирований клиента
CREATE OR REPLACE FUNCTION FN_GET_CLIENT_COMPLETED_BOOKINGS (
    p_client_id IN Client.user_id%TYPE
) RETURN NUMBER IS
    v_bookings_count NUMBER;
BEGIN
    SELECT COUNT(b.id)
    INTO v_bookings_count
    FROM Booking b
    INNER JOIN OrderStatus os ON b.status_id = os.id
    WHERE b.client_id = p_client_id AND os.name = 'completed';
    
    RETURN NVL(v_bookings_count, 0);
END FN_GET_CLIENT_COMPLETED_BOOKINGS;
/



-- Функция 5: Средняя стоимость туров по стране
CREATE OR REPLACE FUNCTION FN_GET_AVG_TOUR_PRICE_BY_COUNTRY (
    p_country_id IN Country.id%TYPE
) RETURN NUMBER IS
    v_avg_price NUMBER;
BEGIN
    SELECT AVG(base_price)
    INTO v_avg_price
    FROM Tour
    WHERE country_id = p_country_id AND is_active = 1;
    
    RETURN NVL(v_avg_price, 0);
END FN_GET_AVG_TOUR_PRICE_BY_COUNTRY;
