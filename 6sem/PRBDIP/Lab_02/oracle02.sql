-- 4. ТРИГГЕРЫ
-- =====================================================
CREATE OR REPLACE TRIGGER TRG_UPDATE_HOTEL_RATING
    FOR INSERT OR UPDATE ON Review
    COMPOUND TRIGGER

    TYPE hotel_ids_t IS TABLE OF Hotel.id%TYPE INDEX BY PLS_INTEGER;
    hotel_ids  hotel_ids_t;
    v_idx      PLS_INTEGER := 0;

    BEFORE STATEMENT IS
    BEGIN
        hotel_ids.DELETE;
        v_idx := 0;
    END BEFORE STATEMENT;

    AFTER EACH ROW IS
        v_hotel_id Hotel.id%TYPE;
    BEGIN
        BEGIN
            SELECT t.hotel_id INTO v_hotel_id
            FROM Tour t
            INNER JOIN Booking b ON t.id = b.tour_id
            WHERE b.id = :NEW.booking_id;

            IF v_hotel_id IS NOT NULL THEN
                hotel_ids(v_idx) := v_hotel_id;
                v_idx := v_idx + 1;
            END IF;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                NULL;
        END;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
    BEGIN
        IF hotel_ids.COUNT > 0 THEN
            FORALL i IN hotel_ids.FIRST..hotel_ids.LAST
                UPDATE Hotel h
                SET rating = (
                    SELECT AVG(r.rating)
                    FROM Review r
                    JOIN Booking b ON r.booking_id = b.id
                    JOIN Tour t ON b.tour_id = t.id
                    WHERE t.hotel_id = hotel_ids(i)
                      AND r.is_approved = 1
                )
                WHERE h.id = hotel_ids(i);
        END IF;
    END AFTER STATEMENT;

END TRG_UPDATE_HOTEL_RATING;
/

