-- Процедура 1: Статистика клиента
CREATE OR REPLACE PROCEDURE SP_GET_CLIENT_STATISTICS (
    p_client_id IN Client.user_id%TYPE,
    p_total_spent OUT NUMBER,
    p_total_bookings OUT NUMBER,
    p_avg_check OUT NUMBER
) IS
BEGIN
    SELECT NVL(SUM(b.total_price), 0),
           COUNT(DISTINCT b.id),
           NVL(AVG(b.total_price), 0)
    INTO p_total_spent, p_total_bookings, p_avg_check
    FROM Booking b
    INNER JOIN OrderStatus os ON b.status_id = os.id
    WHERE b.client_id = p_client_id AND os.name = 'completed';
END SP_GET_CLIENT_STATISTICS;
/

-- Процедура 2: Изменение статуса бронирования
CREATE OR REPLACE PROCEDURE SP_CHANGE_BOOKING_STATUS (
    p_booking_number IN Booking.booking_number%TYPE,
    p_new_status_name IN OrderStatus.name%TYPE
) IS
    v_current_status_id OrderStatus.id%TYPE;
    v_is_final OrderStatus.is_final%TYPE;
    v_new_status_id OrderStatus.id%TYPE;
    v_booking_id Booking.id%TYPE;
BEGIN
    SELECT b.status_id, os.is_final, b.id
    INTO v_current_status_id, v_is_final, v_booking_id
    FROM Booking b
    INNER JOIN OrderStatus os ON b.status_id = os.id
    WHERE b.booking_number = p_booking_number
    FOR UPDATE;

    IF v_is_final = 1 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Cannot change status of a booking that is in a final state.');
    END IF;

    SELECT id INTO v_new_status_id FROM OrderStatus WHERE name = p_new_status_name;

    UPDATE Booking SET status_id = v_new_status_id WHERE booking_number = p_booking_number;
    COMMIT;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20002, 'Booking number or new status name not found.');
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END SP_CHANGE_BOOKING_STATUS;
/

-- Процедура 3: Поиск туров
CREATE OR REPLACE PROCEDURE SP_SEARCH_TOURS (
    p_country_name IN Country.name%TYPE DEFAULT NULL,
    p_min_price IN Tour.base_price%TYPE DEFAULT NULL,
    p_max_price IN Tour.base_price%TYPE DEFAULT NULL,
    p_start_date IN Tour.departure_date%TYPE DEFAULT NULL,
    p_duration IN Tour.duration_days%TYPE DEFAULT NULL,
    p_results OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN p_results FOR
        SELECT
            t.id, t.title, t.base_price, t.duration_days, t.departure_date,
            c.name AS Country, h.name AS Hotel
        FROM Tour t
        INNER JOIN Country c ON t.country_id = c.id
        INNER JOIN Hotel h ON t.hotel_id = h.id
        WHERE t.is_active = 1
          AND (p_country_name IS NULL OR c.name LIKE '%' || p_country_name || '%')
          AND (p_min_price IS NULL OR t.base_price >= p_min_price)
          AND (p_max_price IS NULL OR t.base_price <= p_max_price)
          AND (p_start_date IS NULL OR t.departure_date >= p_start_date)
          AND (p_duration IS NULL OR t.duration_days = p_duration);
END SP_SEARCH_TOURS;
/

-- Процедура 4: Отмена бронирования
CREATE OR REPLACE PROCEDURE SP_CANCEL_BOOKING (
    p_booking_number IN Booking.booking_number%TYPE
) IS
    v_cancelled_status_id OrderStatus.id%TYPE;
    v_booking_id Booking.id%TYPE;
BEGIN
    SELECT id INTO v_cancelled_status_id FROM OrderStatus WHERE name = 'cancelled';
    SELECT id INTO v_booking_id FROM Booking WHERE booking_number = p_booking_number;

    UPDATE Booking SET status_id = v_cancelled_status_id WHERE booking_number = p_booking_number;

    UPDATE Payment
    SET status = 'refunded'
    WHERE booking_id = v_booking_id AND status = 'completed';
    COMMIT;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20003, 'Booking number or cancelled status not found.');
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END SP_CANCEL_BOOKING;
/

-- Процедура 5: Расчет комиссии менеджера
CREATE OR REPLACE PROCEDURE SP_GET_MANAGER_COMMISSION (
    p_manager_id IN Manager.user_id%TYPE,
    p_start_date IN DATE,
    p_end_date IN DATE,
    p_total_commission OUT NUMBER
) IS
BEGIN
    SELECT NVL(SUM(b.total_price * m.commission_rate / 100), 0)
    INTO p_total_commission
    FROM Booking b
    INNER JOIN Manager m ON b.manager_id = m.user_id
    INNER JOIN OrderStatus os ON b.status_id = os.id
    WHERE b.manager_id = p_manager_id
      AND os.name = 'completed'
      AND b.booking_date BETWEEN p_start_date AND p_end_date;
END SP_GET_MANAGER_COMMISSION;
/

