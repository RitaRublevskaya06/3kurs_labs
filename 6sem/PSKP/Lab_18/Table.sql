-- Добавление каскадного удаления и обновления для внешних ключей

-- Пересоздание внешнего ключа для PULPIT с CASCADE
ALTER TABLE PULPIT DROP CONSTRAINT IF EXISTS FK_Pulpits_Facultys;
ALTER TABLE PULPIT ADD CONSTRAINT FK_Pulpits_Facultys 
    FOREIGN KEY (FACULTY) REFERENCES FACULTY(FACULTY) 
    ON DELETE CASCADE ON UPDATE CASCADE;
GO

-- Пересоздание внешнего ключа для TEACHER с CASCADE
ALTER TABLE TEACHER DROP CONSTRAINT IF EXISTS FK_Teachers_Pulpits;
ALTER TABLE TEACHER ADD CONSTRAINT FK_Teachers_Pulpits 
    FOREIGN KEY (PULPIT) REFERENCES PULPIT(PULPIT) 
    ON DELETE CASCADE ON UPDATE CASCADE;
GO

-- Пересоздание внешнего ключа для SUBJECT с CASCADE
ALTER TABLE SUBJECT DROP CONSTRAINT IF EXISTS FK_Subjects_Pulpits;
ALTER TABLE SUBJECT ADD CONSTRAINT FK_Subjects_Pulpits 
    FOREIGN KEY (PULPIT) REFERENCES PULPIT(PULPIT) 
    ON DELETE CASCADE ON UPDATE CASCADE;
GO

-- Пересоздание внешнего ключа для AUDITORIUM с CASCADE
ALTER TABLE AUDITORIUM DROP CONSTRAINT IF EXISTS FK_Auditoriums_AuditoriumsTypes;
