-- Удаление существующих таблиц (если нужно пересоздать)
-- Порядок важен из-за внешних ключей
IF OBJECT_ID('AUDITORIUM', 'U') IS NOT NULL DROP TABLE AUDITORIUM;
IF OBJECT_ID('AUDITORIUM_TYPE', 'U') IS NOT NULL DROP TABLE AUDITORIUM_TYPE;
IF OBJECT_ID('SUBJECT', 'U') IS NOT NULL DROP TABLE SUBJECT;
IF OBJECT_ID('TEACHER', 'U') IS NOT NULL DROP TABLE TEACHER;
IF OBJECT_ID('PULPIT', 'U') IS NOT NULL DROP TABLE PULPIT;
IF OBJECT_ID('FACULTY', 'U') IS NOT NULL DROP TABLE FACULTY;
GO

-- Создание таблицы FACULTY (факультеты)
CREATE TABLE FACULTY
(
    FACULTY INT PRIMARY KEY,
    FACULTY_NAME NVARCHAR(30)  -- Используем NVARCHAR вместо NCHAR
);
GO

-- Создание таблицы PULPIT (кафедры)
CREATE TABLE PULPIT
(
    PULPIT INT PRIMARY KEY,
    PULPIT_NAME NVARCHAR(30),  -- Используем NVARCHAR вместо NCHAR
    FACULTY INT,
    CONSTRAINT FK_Pulpits_Facultys FOREIGN KEY (FACULTY) REFERENCES FACULTY(FACULTY)
);
GO

-- Создание таблицы TEACHER (преподаватели)
CREATE TABLE TEACHER
(
    TEACHER INT PRIMARY KEY,
    TEACHER_NAME NVARCHAR(30),  -- Используем NVARCHAR вместо NCHAR
    PULPIT INT,
    CONSTRAINT FK_Teachers_Pulpits FOREIGN KEY (PULPIT) REFERENCES PULPIT(PULPIT)
);
GO

-- Создание таблицы SUBJECT (дисциплины)
CREATE TABLE SUBJECT
(
    SUBJECT INT PRIMARY KEY,
    SUBJECT_NAME NVARCHAR(30),  -- Используем NVARCHAR вместо NCHAR
    PULPIT INT,
    CONSTRAINT FK_Subjects_Pulpits FOREIGN KEY (PULPIT) REFERENCES PULPIT(PULPIT)
);
GO

-- Создание таблицы AUDITORIUM_TYPE (типы аудиторий)
CREATE TABLE AUDITORIUM_TYPE
(
    AUDITORIUM_TYPE INT PRIMARY KEY,
    AUDITORIUM_TYPENAME NVARCHAR(30)  -- Используем NVARCHAR вместо NCHAR
);
GO

-- Создание таблицы AUDITORIUM (аудитории)
CREATE TABLE AUDITORIUM
(
    AUDITORIUM INT PRIMARY KEY,
    AUDITORIUM_NAME NVARCHAR(30),  -- Используем NVARCHAR вместо NCHAR
    AUDITORIUM_CAPACITY INT,
    AUDITORIUM_TYPE INT,
    CONSTRAINT FK_Auditoriums_AuditoriumsTypes FOREIGN KEY (AUDITORIUM_TYPE) REFERENCES AUDITORIUM_TYPE(AUDITORIUM_TYPE)
);
GO

